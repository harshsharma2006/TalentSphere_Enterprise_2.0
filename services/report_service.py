"""
TalentSphere Enterprise 2.0 - Report Service
Enterprise PDF Report Generation via ReportLab and CSV Data Exporter.
"""

import os
import io
import pandas as pd
from datetime import datetime
from typing import List, Dict, Any
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from core.config import settings

class ReportService:
    @staticmethod
    def generate_talent_summary_pdf(employees: List[Dict[str, Any]], title: str = "Enterprise Talent Review Summary") -> bytes:
        """Generates an executive-ready PDF report of enterprise workforce."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()
        primary_color = colors.HexColor("#2563EB")
        dark_blue = colors.HexColor("#174A82")
        neutral_dark = colors.HexColor("#1E293B")

        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            fontSize=22,
            leading=26,
            textColor=dark_blue,
            spaceAfter=4
        )
        subtitle_style = ParagraphStyle(
            'ReportSubtitle',
            parent=styles['Normal'],
            fontSize=10,
            textColor=colors.HexColor("#64748B"),
            spaceAfter=15
        )
        cell_style = ParagraphStyle(
            'ReportCell',
            parent=styles['Normal'],
            fontSize=9,
            leading=12,
            textColor=neutral_dark
        )

        elements = []
        # Header
        elements.append(Paragraph(f"<b>TalentSphere Enterprise 2.0</b>", title_style))
        elements.append(Paragraph(f"{title} | Generated: {datetime.now().strftime('%B %d, %Y - %H:%M')}", subtitle_style))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=primary_color, spaceBefore=0, spaceAfter=15))

        # Table Data
        table_data = [
            [
                Paragraph("<b>Code</b>", cell_style),
                Paragraph("<b>Name</b>", cell_style),
                Paragraph("<b>Designation</b>", cell_style),
                Paragraph("<b>Department</b>", cell_style),
                Paragraph("<b>Location</b>", cell_style)
            ]
        ]

        for emp in employees:
            table_data.append([
                Paragraph(emp.get("employee_code", ""), cell_style),
                Paragraph(emp.get("full_name", ""), cell_style),
                Paragraph(emp.get("designation", ""), cell_style),
                Paragraph(emp.get("department", ""), cell_style),
                Paragraph(emp.get("work_location", ""), cell_style),
            ])

        if len(table_data) == 1:
            table_data.append([Paragraph("No records found.", cell_style), "", "", "", ""])

        report_table = Table(table_data, colWidths=[65, 120, 145, 120, 90])
        report_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#EFF6FF")),
            ('TEXTCOLOR', (0, 0), (-1, 0), dark_blue),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
            ('TOPPADDING', (0, 0), (-1, 0), 8),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ]))

        elements.append(report_table)
        elements.append(Spacer(1, 25))
        elements.append(Paragraph(f"Confidential • Generated by TalentSphere Enterprise v{settings.APP_VERSION}", subtitle_style))

        doc.build(elements)
        buffer.seek(0)
        return buffer.getvalue()

    @staticmethod
    def generate_students_placement_pdf(students: List[Dict[str, Any]]) -> bytes:
        """Generates a placement readiness PDF report for College Administrators."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()
        dark_blue = colors.HexColor("#174A82")
        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            fontSize=20,
            leading=24,
            textColor=dark_blue,
            spaceAfter=4
        )
        subtitle_style = ParagraphStyle(
            'ReportSubtitle',
            parent=styles['Normal'],
            fontSize=10,
            textColor=colors.HexColor("#64748B"),
            spaceAfter=15
        )
        cell_style = ParagraphStyle(
            'ReportCell',
            parent=styles['Normal'],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#1E293B")
        )

        elements = [
            Paragraph("<b>TalentSphere Enterprise 2.0</b>", title_style),
            Paragraph(f"Student Placement Readiness Report • {datetime.now().strftime('%B %d, %Y')}", subtitle_style),
            HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563EB"), spaceBefore=0, spaceAfter=15)
        ]

        table_data = [
            [
                Paragraph("<b>ID</b>", cell_style),
                Paragraph("<b>Student Name</b>", cell_style),
                Paragraph("<b>Department</b>", cell_style),
                Paragraph("<b>GPA</b>", cell_style),
                Paragraph("<b>Readiness %</b>", cell_style),
                Paragraph("<b>Status</b>", cell_style)
            ]
        ]

        for s in students:
            table_data.append([
                Paragraph(s.get("student_id_number", ""), cell_style),
                Paragraph(s.get("full_name", ""), cell_style),
                Paragraph(s.get("department", ""), cell_style),
                Paragraph(str(s.get("gpa", "")), cell_style),
                Paragraph(f"{s.get('placement_readiness_score', 0)}%", cell_style),
                Paragraph(s.get("placement_status", ""), cell_style),
            ])

        report_table = Table(table_data, colWidths=[65, 130, 130, 45, 75, 95])
        report_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#EFF6FF")),
            ('TEXTCOLOR', (0, 0), (-1, 0), dark_blue),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ]))

        elements.append(report_table)
        doc.build(elements)
        buffer.seek(0)
        return buffer.getvalue()

    @staticmethod
    def export_csv(records: List[Dict[str, Any]]) -> str:
        """Converts dictionary records into CSV string."""
        if not records:
            return ""
        df = pd.DataFrame(records)
        return df.to_csv(index=False)
